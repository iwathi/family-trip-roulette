let dataFile = fs.readFileSync('data.js', 'utf-8');
const jsonStr = dataFile.replace('const prefectureData = ', '').replace(/;/g, '').trim();
const data = JSON.parse(jsonStr);

let spotCount = 0;

data.forEach(pref => {
    const additionalSpots = zekkeiSpots[pref.name] || [];
    
    // Merge without exact duplicates
    additionalSpots.forEach(newSpot => {
        if (!pref.spots.includes(newSpot)) {
            pref.spots.push(`🌟[絶景] ${newSpot}`);
            spotCount++;
        }
    });
    
    // Let's also ensure the genre reflects these awesome additions if needed, but it's fine as is.
    if (!pref.genre.includes("絶景")) {
        pref.genre = pref.genre + "・絶景";
    }
});

console.log(`Added ${spotCount} zekkei spots!`);

const output = 'const prefectureData = ' + JSON.stringify(data, null, 4) + ';';
fs.writeFileSync('data.js', output);
